// Package docgen writes the two chapters of the manual that are lists
// of what the engine has: every function of the formula language, from
// the catalogue the engine itself reads, and every code of a refusal,
// from the constants the engine answers with and their comments. They
// are generated so that they cannot fall behind the engine: a test
// compares the files with what this package writes, and
//
//	make docs
//
// writes them again after a change.
package docgen

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/MojoHand70/fadodb/internal/formula"
)

const generated = "<!-- Generated by internal/docgen from the engine's own tables. Do not edit: run `make docs`. -->\n\n"

// categories are the groups of the function catalogue, in the order the
// chapter shows them, each with its heading and one line about it.
var categories = []struct{ key, title, about string }{
	{"logic", "Logic", "Conditions, and what to answer when something is missing or fails."},
	{"numeric", "Numbers", "Arithmetic on numbers as a spreadsheet keeps them."},
	{"exact", "Exact numbers and money", "Amounts that must come out to the cent."},
	{"text", "Text", "Building, cutting and searching text."},
	{"date", "Dates and times", "Calendar days and moments."},
	{"composite", "Lists, objects and rows", "Values that hold several values."},
	{"context", "The caller, the clock and the document", "Who is calling, what time it is, and what the engine keeps about the document: its state, who made it, when it entered a state."},
	{"data", "Tables and other documents", "Values looked up outside the document."},
}

// Functions is the chapter that lists every function.
func Functions() string {
	var b strings.Builder
	b.WriteString(generated)
	b.WriteString("# The functions\n\n")
	b.WriteString("Every function a formula can call, by what it is for. The list is written\nfrom the engine's own catalogue, so it has every function and no other.\n\n")
	b.WriteString("A name is written in capitals and matches in any case. An argument in\nsquare brackets may be left out, and `...` means it may be repeated.\nA function marked **not built yet** is part of the language and is\nrefused by this version of the engine.\n\n")

	b.WriteString("## Where a function may stand\n\nEach function is of one kind, which decides where it may be used.\n\n| Kind | Meaning |\n|---|---|\n")
	classes := formula.Classes()
	for _, class := range []formula.Class{"pure", "context", "lookup", "query", "secret"} {
		if text, ok := classes[class]; ok {
			fmt.Fprintf(&b, "| %s | %s |\n", class, cell(text))
		}
	}
	b.WriteString("\nAn auto formula is the formula of a computed variable that the engine\nworks out again whenever a value it reads changes.\n\n")

	byCategory := map[string][]*formula.Function{}
	for _, fn := range formula.Functions() {
		byCategory[fn.Category] = append(byCategory[fn.Category], fn)
	}
	known := map[string]bool{}
	for _, c := range categories {
		known[c.key] = true
		fns := byCategory[c.key]
		if len(fns) == 0 {
			continue
		}
		fmt.Fprintf(&b, "## %s\n\n%s\n\n| Function | Kind | Answers |\n|---|---|---|\n", c.title, c.about)
		for _, fn := range fns {
			answers := cell(fn.Summary)
			if len(fn.Aliases) > 0 {
				answers += " Also written " + strings.Join(code(fn.Aliases), ", ") + "."
			}
			if !formula.Implemented(fn.Name) {
				answers += " **Not built yet.**"
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s |\n", fn.Signature(fn.Name), fn.Class, answers)
		}
		b.WriteString("\n")
	}
	// A category the catalogue gains is shown, at the end, until this
	// file gives it a heading.
	var rest []string
	for key := range byCategory {
		if !known[key] {
			rest = append(rest, key)
		}
	}
	sort.Strings(rest)
	for _, key := range rest {
		fmt.Fprintf(&b, "## %s\n\n| Function | Kind | Answers |\n|---|---|---|\n", key)
		for _, fn := range byCategory[key] {
			fmt.Fprintf(&b, "| `%s` | %s | %s |\n", fn.Signature(fn.Name), fn.Class, cell(fn.Summary))
		}
		b.WriteString("\n")
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}

// A source of codes: a file of the engine, the prefix of its constants,
// and the heading and the words the chapter gives its list.
type source struct {
	file, prefix, title, about string
}

var sources = []source{
	{"store/errors.go", "Code", "Refusals of a call",
		"What a call is answered with when the engine does not carry it out: a create, a set, a transition, a read. Nothing is written when a command is refused."},
	{"model/diagnostic.go", "Code", "Findings in a definition",
		"What the engine reports when it checks a class, a table, a schema or an action before defining it. Every finding of a definition is reported at once, each with its place in the definition."},
	{"formula/vm.go", "Err", "Errors of a formula",
		"What a formula stops with when it cannot give a value. Inside a commit the refusal carries this code and names the variable whose formula failed."},
}

// Refusals is the chapter that lists every code. root is the directory
// that holds the engine's packages, internal.
func Refusals(root string) (string, error) {
	var b strings.Builder
	b.WriteString(generated)
	b.WriteString("# The refusals\n\n")
	b.WriteString("Every code the engine answers with when it does not do what it was\nasked, and what each means. The list is written from the engine's own\nconstants, so it has every code and no other.\n\n")
	b.WriteString("A refusal has four parts.\n\n| Part | What it is |\n|---|---|\n")
	b.WriteString("| the code | one of the words below; it never changes, so a program or an agent can act on it |\n")
	b.WriteString("| the place | the variable, or the place in the class definition, that the refusal is about, such as `/access/update` |\n")
	b.WriteString("| the message | what happened, in words, for a person |\n")
	b.WriteString("| the hint | often, what to do about it |\n\n")
	b.WriteString("The same word can appear in more than one list: `forbidden` is always\nabout who may, wherever it comes from.\n\n")
	for _, src := range sources {
		codes, err := codesOf(filepath.Join(root, filepath.FromSlash(src.file)), src.prefix)
		if err != nil {
			return "", err
		}
		if len(codes) == 0 {
			return "", fmt.Errorf("docgen: no codes found in %s", src.file)
		}
		fmt.Fprintf(&b, "## %s\n\n%s\n\n| Code | Meaning |\n|---|---|\n", src.title, src.about)
		for _, c := range codes {
			fmt.Fprintf(&b, "| `%s` | %s |\n", c.value, cell(c.meaning))
		}
		b.WriteString("\n")
	}
	return strings.TrimRight(b.String(), "\n") + "\n", nil
}

type codeDoc struct{ value, meaning string }

// codesOf reads the string constants of a file whose names start with
// the prefix, in the order they are declared, each with its comment as
// its meaning. A constant without a comment is an error: the comment is
// the manual's line.
func codesOf(path, prefix string) ([]codeDoc, error) {
	file, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	var out []codeDoc
	for _, decl := range file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.CONST {
			continue
		}
		for _, spec := range gen.Specs {
			vs, ok := spec.(*ast.ValueSpec)
			if !ok || len(vs.Names) != 1 || len(vs.Values) != 1 {
				continue
			}
			name := vs.Names[0].Name
			lit, ok := vs.Values[0].(*ast.BasicLit)
			if !ok || lit.Kind != token.STRING || !strings.HasPrefix(name, prefix) || !ast.IsExported(name) {
				continue
			}
			value, err := strconv.Unquote(lit.Value)
			if err != nil {
				return nil, err
			}
			if vs.Doc == nil {
				return nil, fmt.Errorf("docgen: %s in %s has no comment; its comment is its line in the manual", name, filepath.Base(path))
			}
			meaning := strings.Join(strings.Fields(vs.Doc.Text()), " ")
			// A comment begins with the constant's name and a colon.
			meaning = strings.TrimSpace(strings.TrimPrefix(meaning, name+":"))
			if meaning == "" {
				return nil, fmt.Errorf("docgen: the comment of %s in %s says nothing", name, filepath.Base(path))
			}
			out = append(out, codeDoc{value: value, meaning: strings.ToUpper(meaning[:1]) + meaning[1:]})
		}
	}
	return out, nil
}

// cell makes a text safe for the cell of a table.
func cell(text string) string {
	return strings.ReplaceAll(strings.Join(strings.Fields(text), " "), "|", `\|`)
}

func code(names []string) []string {
	out := make([]string, len(names))
	for i, n := range names {
		out[i] = "`" + n + "`"
	}
	return out
}
